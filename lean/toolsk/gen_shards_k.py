#!/usr/bin/env python3
"""gen_shards_k.py SWEEPDIR OUTROOT TARGET_KERNEL_S RATIO [--native]

Kernel (decide +kernel, default) or native (native_decide, --native) shards of the 611 upper bound with checker v4.
Untrusted: Lean re-checks contiguity and coverage (baseOK4) and every shard (segOK4).

* For every segment (LDEN, k) of the sweep (lines `k lo m spec ws npieces R gen_ms ok check_ms`) the Taylor order with
  the smallest native check time is used.
* Segments are split into sub-segments of consecutive pieces, at most floor(TARGET / (RATIO * native s per piece))
  pieces each (at least 1), so that a shard takes about TARGET kernel seconds (memory grows with kernel time).
Writes SUCert/UpperCfgK.lean (cfgK, segsK), SignUnc/UpperShardsK{,N}/S<i>.lean, SignUnc/UpperMainK{,N}.lean and
data/k_shards.check (genjet check lines), relative to OUTROOT.
"""
import sys, os, glob, hashlib

sweep, root, target, ratio = sys.argv[1], sys.argv[2], float(sys.argv[3]), float(sys.argv[4])
native = '--native' in sys.argv
tac = 'native_decide' if native else 'decide +kernel'
sfx = 'N' if native else ''

best = {}
for f in sorted(glob.glob(os.path.join(sweep, 's_*_m*.txt'))):
    den = int(os.path.basename(f).split('_')[1])
    for l in open(f):
        p = l.split()
        if len(p) < 10 or p[8] != 'true':
            continue
        key = (den, int(p[0]))
        ms = int(p[9])
        if key not in best or ms < best[key][0]:
            best[key] = (ms, p)
# order segments by start
segs = sorted(best.values(), key=lambda v: int(v[1][1]))

def lit(n):
    return f"(Int.negSucc {-n - 1})" if n < 0 else f"({n} : Int)"

subs = []  # (lo, m, spec, runs, est_ms)
for ms, p in segs:
    lo, m, spec, ws = int(p[1]), int(p[2]), p[3], p[4]
    runs = [tuple(map(int, t.split(':'))) for t in ws.split(',')]
    widths = [w for w, c in runs for _ in range(c)]
    per = ms / len(widths) / 1000.0
    npmax = max(1, int(target / (ratio * per)))
    i = 0
    while i < len(widths):
        chunk = widths[i:i + npmax]
        rr = []
        for w in chunk:
            if rr and rr[-1][0] == w:
                rr[-1][1] += 1
            else:
                rr.append([w, 1])
        subs.append((lo, m, spec, rr, per * 1000 * len(chunk)))
        lo += sum(chunk)
        i += npmax

# contiguity sanity (Lean re-checks)
for a, b in zip(subs, subs[1:]):
    assert a[0] + sum(w * c for w, c in a[3]) == b[0]

def seg_lit(s):
    lo, m, spec, rr, _ = s
    sps = ", ".join(f"⟨{a}, {b}, {c}, {'true' if d == '1' else 'false'}⟩"
                    for a, b, c, d in (t.split(',') for t in spec.split(';')))
    wsl = ", ".join(f"({w}, {c})" for w, c in rr)
    return f"(⟨{lit(lo)}, {m}, [{sps}], [{wsl}]⟩ : Seg4)"

os.makedirs(os.path.join(root, 'SUCert'), exist_ok=True)
if not native:
    cfg = ["import SUCert.JetK", "",
           f"/-! Generated by toolsk/gen_shards_k.py (target {target} kernel s per shard, ratio {ratio}): run parameters and",
           "the segment chain of the upper-bound check with checker v4. -/", "",
           "namespace SignUnc.UpperRunK", "open SignUnc.Chk", "",
           "/-- P n k rn rd Yn Yd w cnt depth (w, cnt unused). -/",
           "def cfgK : Cfg := ⟨128, 24, 4, 5509, 10000, 92, 1, 0, 0, 8⟩", "",
           "def segsK : List Seg4 := ["]
    cfg += ["  " + seg_lit(s) + ("," if i + 1 < len(subs) else "") for i, s in enumerate(subs)]
    cfg += ["]", "", "end SignUnc.UpperRunK", ""]
    open(os.path.join(root, 'SUCert', 'UpperCfgK.lean'), 'w').write("\n".join(cfg))
    with open(os.path.join(root, 'data', 'k_shards.check'), 'w') as f:
        for i, s in enumerate(subs):
            lo, m, spec, rr, est = s
            f.write(f"{i} {lo} {m} {spec} {','.join(f'{w}:{c}' for w, c in rr)} {sum(c for _, c in rr)} 0 0\n")

sd = os.path.join(root, 'SignUnc', f'UpperShardsK{sfx}')
os.makedirs(sd, exist_ok=True)
for i, s in enumerate(subs):
    body = ["import SUCert.UpperCfgK", "import SUCert.DataGroups", "",
            "namespace SignUnc.UpperRunK", "open SignUnc.Chk SignUnc.Data", ""]
    if not native:
        body += ["set_option maxHeartbeats 0", "set_option maxRecDepth 1000000", ""]
    body += [f"theorem shardK{sfx}_{i} : segOK4 cfgK upperGroups {seg_lit(s)} = true := by {tac}", "",
             "end SignUnc.UpperRunK", ""]
    open(os.path.join(sd, f'S{i}.lean'), 'w').write("\n".join(body))

base = ["import SUCert.UpperCfgK", "import SUCert.DataGroups", "", "namespace SignUnc.UpperRunK",
        "open SignUnc.Chk SignUnc.Data", "", "set_option maxHeartbeats 0", "set_option maxRecDepth 1000000", "",
        f"theorem baseK{sfx} : baseOK4 cfgK (flatOfGroups upperGroups) segsK = true := by {tac}", "",
        "end SignUnc.UpperRunK", ""]
open(os.path.join(sd, 'Base.lean'), 'w').write("\n".join(base))
imports = "\n".join([f"import SignUnc.UpperShardsK{sfx}.Base"] +
                    [f"import SignUnc.UpperShardsK{sfx}.S{i}" for i in range(len(subs))])
conj = ", ".join(f"shardK{sfx}_{i}" for i in range(len(subs)))
main = f"""import SignUnc.UpperK
import SignUnc.APos
import SUCert.UpperCfgK
import SUCert.DataGroups
{imports}

/-!
# `A₊(1)² ≤ 0.5509²` and `C_{{6.11}} ≤ 0.5509²` with checker v4 ({'native_decide' if native else 'kernel only: decide +kernel'})
-/

namespace SignUnc.UpperRunK
open SignUnc SignUnc.Chk SignUnc.Data

set_option maxRecDepth 100000 in
theorem shardsK{sfx} : List.Forall (fun s => segOK4 cfgK upperGroups s = true) segsK :=
  ⟨{conj}⟩

end SignUnc.UpperRunK

namespace SignUnc
open SignUnc.Chk SignUnc.Data SignUnc.UpperRunK

/-- The upper half of Theorem 1.1 of the paper (checker v4: order-m Taylor models). -/
theorem upperK{sfx} : UpperStatement := by
  obtain ⟨hL, h0, hpos⟩ := upper_v4_sound cfgK upperGroups segsK baseK{sfx} shardsK{sfx}
  have hr : ((cfgK.rn : ℝ) / cfgK.rd) = 5509 / 10000 := by norm_num [cfgK]
  exact upper_of_gsum (r := 5509 / 10000) (by norm_num) _ hL h0
    (fun y hy => (hpos y (by rw [hr]; exact hy)).le)

end SignUnc
"""
open(os.path.join(root, 'SignUnc', f'UpperMainK{sfx}.lean'), 'w').write(main)
tot = sum(s[4] for s in subs) / 1000.0
print(f"{len(segs)} segments -> {len(subs)} shards; est native {tot:.1f} s, est kernel {tot*ratio/3600:.1f} CPU-h;",
      f"max est kernel per shard {max(s[4] for s in subs)*ratio/1000:.0f} s")
