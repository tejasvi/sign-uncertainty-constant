#!/usr/bin/env python3
"""Generate SUCert/LowData.lean (lower-bound certificate data for the Lean checker) from cert_r05502_K35.json.

Gaussian pairs are grouped by width on arithmetic grids (checked exactly); cosines and psi are copied as exact
fractions.  The approximant P of phi is generated separately by the Lean exe `genlow mkp` (SUCert/LowP.lean).
Usage: python3 -I tools/gen_lower_data.py CERT OUT
"""
import sys, json, hashlib
from fractions import Fraction as Fr

PB = 128

def lean_int(x):
    return f"(({x} : Int))" if x >= 0 else f"(Int.negSucc {-x - 1})"

def main(cert, out):
    raw = open(cert, 'rb').read()
    sha = hashlib.sha256(raw).hexdigest()
    d = json.loads(raw)
    r = Fr(d['r'])
    assert r == Fr(2751, 5000)
    pairs = []
    for a, s, c, k in d['gauss']:
        assert k == 0
        pairs.append((Fr(a), Fr(s), Fr(c)))
    # groups by width
    widths = sorted(set(a for a, s, c in pairs))
    groups = []
    for a in widths:
        ps = sorted([(s, c) for aa, s, c in pairs if aa == a])
        s0 = ps[0][0]
        if len(ps) == 1:
            dl = Fr(1)
        else:
            dl = ps[1][0] - ps[0][0]
        for i, (s, c) in enumerate(ps):
            assert s == s0 + i * dl, (a, i, s)
        groups.append((a, s0, dl, [c for s, c in ps]))
    coss = [(Fr(b), Fr(dd)) for b, dd in d['pm']]
    psi = [Fr(x) for x in d['psi']]
    L = []
    L.append("import SUCert.Jet")
    L.append("")
    L.append(f"/-! Generated by tools/gen_lower_data.py from cert_r05502_K35.json (sha256 {sha}). -/")
    L.append("")
    L.append("namespace SignUnc.LowData")
    L.append("open SignUnc.Chk")
    L.append("")
    for gi, (a, s0, dl, cs) in enumerate(groups):
        L.append(f"def lgrp{gi} : GGroup := ⟨{a.numerator}, {a.denominator}, ({lean_int(s0.numerator)} : Int), "
                 f"{s0.denominator}, {dl.numerator}, {dl.denominator}, [")
        L.append(",\n".join(f"    (({lean_int(c.numerator)}, {c.denominator}) : Int × Nat)" for c in cs))
        L.append("  ]⟩")
        L.append("")
    L.append("def lowGroups : List GGroup := [" + ", ".join(f"lgrp{i}" for i in range(len(groups))) + "]")
    L.append("")
    L.append("/-- Cosines `(β, d)` as fractions `(βn, βd, dn, dd)`. -/")
    L.append("def lowCos : List (Nat × Nat × Int × Nat) := [" + ", ".join(
        f"({b.numerator}, {b.denominator}, {lean_int(dd.numerator)}, {dd.denominator})" for b, dd in coss) + "]")
    L.append("")
    L.append("/-- `ψ(x) = Σ_k q_k x^(2k)`, `q_k = num/den`. -/")
    L.append("def lowPsi : List (Int × Nat) := [" + ", ".join(
        f"({lean_int(q.numerator)}, {q.denominator})" for q in psi) + "]")
    L.append("")
    L.append("end SignUnc.LowData")
    L.append("")
    open(out, 'w').write("\n".join(L))
    print(f"groups {[(float(a), float(s0), float(dl), len(cs)) for a, s0, dl, cs in groups]}")

if __name__ == '__main__':
    main(*sys.argv[1:3])
