#!/usr/bin/env python3
"""Generate the kernel (K) shards of the lower check and their glue.

Writes SignUnc/LowShardsK/{B_m20,B_m16,B_p0..B_p18,B_rho,B_tail,B_misc,S0..S117}.lean (core Lean only, `decide +kernel`)
and SignUnc/LowShardsK.lean (glue: lowBase_okK, lowSegs_okK), plus tools/lowshards_k.jobs (name, estimated kernel s).
Inputs: SUCert/LowSegs.lean (segments) and data/low_gen/*.txt (native ms per segment, for the estimates).
Usage: python3 -I tools/gen_lowshards_k.py
"""
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
segtxt = open(os.path.join(ROOT, 'SUCert/LowSegs.lean')).read()
segs = {}
for m in re.finditer(r'/-- segment (\S+) \((\S+)\) -/\ndef lseg(\d+) : LSeg := ⟨\((-?\d+) : Int\), (\d+), (\d+), ', segtxt):
    segs[int(m.group(3))] = dict(file=m.group(2), M=int(m.group(5)), N=int(m.group(6)))
nseg = len(segs)
assert sorted(segs) == list(range(nseg))
for i, s in segs.items():
    line = open(os.path.join(ROOT, 'data/low_gen', s['file'])).read().split('\n')[0].split(' ')
    s['native_ms'] = int(line[-1])
    assert s['M'] in (16, 20) and (s['M'] == 20) == (s['N'] == 25) and s['N'] <= 135, (i, s)

outd = os.path.join(ROOT, 'SignUnc/LowShardsK')
os.makedirs(outd, exist_ok=True)
HDR = '''import SignUnc.LowK.Defs

namespace SignUnc.LowData
open SignUnc.Chk

set_option maxHeartbeats 0
set_option maxRecDepth 1000000

'''
def write(name, body):
    open(os.path.join(outd, name + '.lean'), 'w').write(HDR + body + '\nend SignUnc.LowData\n')

jobs = []
write('B_m20', 'theorem km20 : lowP.map (pieceMoms 128 20 25) = MomsLit20 := by decide +kernel\n'); jobs.append(('B_m20', 80))
write('B_m16', 'theorem km16 : lowP.map (pieceMoms 128 16 135) = MomsLit16 := by decide +kernel\n'); jobs.append(('B_m16', 300))
NP = 19
for i in range(NP):
    write('B_p%d' % i, 'theorem kpp_%d : ppOK 128 24 4 24 8 lowGroups lowCos lowPsi lowEps (lowPS.getD %d ((0, 0, []), [])) = true := by\n  decide +kernel\n' % (i, i))
    jobs.append(('B_p%d' % i, 30))
write('B_rho', 'theorem krho : rhoOK 128 30 lowPsi lowP lowEps lowDelta = true := by decide +kernel\n'); jobs.append(('B_rho', 50))
write('B_tail', 'theorem ktail : ltailOK lowCfg lowGroups lowCos lowP = true := by decide +kernel\n'); jobs.append(('B_tail', 10))
write('B_misc', '''theorem kmisc : chainOK 0 lowP = true ∧ lowP.length = lowPSS.length ∧ lowPS.length = %d ∧
    (match lcontigEnd ((2751 * 2 ^ lowCfg.P / 5000 : Nat) : Int) lowSegs with
      | some e => decide (((lowCfg.YT * 2 ^ lowCfg.P : Nat) : Int) ≤ e)
      | none => false) = true := by
  decide +kernel
''' % NP); jobs.append(('B_misc', 10))
for i in range(nseg):
    s = segs[i]
    write('S%d' % i, 'theorem ks_%d : lsegM lowCfg lowGroups lowCos lowP lseg%d (momsFor %d %d) = true := by\n  decide +kernel\n'
          % (i, i, s['M'], s['N']))
    jobs.append(('S%d' % i, int(84 * s['native_ms'] / 1000) + 5))

# glue
L = ['import SignUnc.LowK.Glue']
L += ['import SignUnc.LowShardsK.%s' % j[0] for j in jobs]
L.append('''
/-!
# The lower-bound shards, kernel track: `lowBase_okK` and `lowSegs_okK`

Every shard module (`SignUnc/LowShardsK/*.lean`, core Lean only) is a `decide +kernel` check; this module assembles
them. Generated by `tools/gen_lowshards_k.py`.
-/

namespace SignUnc.LowData
open SignUnc.Chk
''')
for i in range(nseg):
    s = segs[i]
    if s['M'] == 20:
        hm = 'momsFor20 km20'
    else:
        hm = 'momsFor16 (by decide) km16'
    L.append('theorem lseg_okK_%d : lsegOK lowCfg lowGroups lowCos lowP lseg%d = true :=\n  lsegOK_of_lsegM (%s) ks_%d\n' % (i, i, hm, i))
L.append('''theorem lowSegs_allK : lowSegs.all (fun s => lsegOK lowCfg lowGroups lowCos lowP s) = true := by
  simp only [lowSegs, List.all_cons, List.all_nil, Bool.and_true, %s]

theorem lowSegs_okK : ∀ s ∈ lowSegs, lsegOK lowCfg lowGroups lowCos lowP s = true :=
  List.all_eq_true.mp lowSegs_allK
''' % ', '.join('lseg_okK_%d' % i for i in range(nseg)))
cases = '\n'.join('    | %d, _ => exact kpp_%d' % (i, i) for i in range(NP))
L.append('''theorem lowBase_okK : lbaseOK lowCfg lowGroups lowCos lowPsi lowP lowPSS lowSegs = true := by
  obtain ⟨hchain, hlen, hlen19, hcontig⟩ := kmisc
  have hzip : lowP.zip lowPSS = lowPS := zip_map_fst_snd lowPS
  have hall : ∀ x ∈ lowPS, ppOK 128 24 4 24 8 lowGroups lowCos lowPsi lowEps x = true := by
    apply all_of_getD lowPS ((0, 0, []), [])
    intro i hi
    rw [hlen19] at hi
    match i, hi with
%s
    | i + %d, h => exact absurd h (by omega)
  have hne : lowP.zip lowPSS ≠ [] := by
    rw [hzip]
    exact List.ne_nil_of_length_pos (by rw [hlen19]; decide)
  have hp : pOK 128 24 4 24 8 lowGroups lowCos lowPsi lowEps lowP lowPSS = true :=
    pOK_of hchain hlen hne (by rw [hzip]; exact hall)
  unfold lbaseOK
  simp only [Bool.and_eq_true]
  exact ⟨⟨⟨hp, krho⟩, ktail⟩, hcontig⟩

end SignUnc.LowData
''' % (cases, NP))
open(os.path.join(ROOT, 'SignUnc/LowShardsK.lean'), 'w').write('\n'.join(L))
with open(os.path.join(ROOT, 'tools/lowshards_k.jobs'), 'w') as f:
    for name, est in jobs:
        f.write('%s %d\n' % (name, est))
print('shards', len(jobs), 'est kernel s total', sum(e for _, e in jobs))
