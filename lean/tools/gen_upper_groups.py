#!/usr/bin/env python3
"""Generate SUCert/DataGroups.lean (grouped Gaussian pairs) from the upper-bound certificate (pcert JSON).

Groups: the pairs with a common width a, in order of first appearance of the width, each with centres on an arithmetic
grid s_k = s0 + k*Delta (checked here; the Lean side re-checks the match with the flat data, matchFlat).  A width with a
single pair gets Delta = 1.  Negative integers are written Int.negSucc k.
Usage: python3 -I gen_upper_groups.py CERT.json OUT.lean
"""
import json, sys, hashlib
from fractions import Fraction as F

def lit(n):
    return f"(Int.negSucc {-n - 1})" if n < 0 else f"({n} : Int)"

def main(cert, out):
    raw = open(cert, 'rb').read()
    d = json.loads(raw)
    T = [(F(a), F(s), F(c)) for a, s, c in d["gauss"]]
    widths = []
    for a, _, _ in T:
        if a not in widths:
            widths.append(a)
    lines = ["import SUCert.Grid", "",
             f"/-! Generated by tools/gen_upper_groups.py from {cert.split('/')[-1]} (sha256 {hashlib.sha256(raw).hexdigest()}). -/",
             "", "namespace SignUnc.Data", "open SignUnc.Chk", ""]
    names = []
    for gi, a in enumerate(widths):
        lst = [(s, c) for (aa, s, c) in T if aa == a]
        s0 = lst[0][0]
        dlt = (lst[1][0] - lst[0][0]) if len(lst) > 1 else F(1)
        assert dlt > 0 and all(lst[i][0] == s0 + i * dlt for i in range(len(lst)))
        cs = ",\n    ".join(f"(({lit(c.numerator)}, {c.denominator}) : Int × Nat)" for _, c in lst)
        lines.append(f"def grp{gi} : GGroup := ⟨{a.numerator}, {a.denominator}, {lit(s0.numerator)}, {s0.denominator}, "
                     f"{dlt.numerator}, {dlt.denominator}, [\n    {cs}]⟩")
        lines.append("")
        names.append(f"grp{gi}")
    # the wide pair (smallest width, a single pair) must be the LAST group for matchFlat
    amin = min(widths)
    wi = widths.index(amin)
    order = [n for i, n in enumerate(names) if i != wi] + [names[wi]]
    lines.append("def upperGroups : List GGroup := [" + ", ".join(order) + "]")
    lines += ["", "end SignUnc.Data", ""]
    open(out, 'w').write("\n".join(lines))
    print(len(names), "groups ->", out)

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
